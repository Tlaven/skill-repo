#!/usr/bin/env python3
r"""等待专用 profile 完成 Google 登录 -> 自动导出 cookies.txt

用法:
    1) 先启动专用 Chrome (由 agent/用户手动):
       chrome.exe --user-data-dir=%LOCALAPPDATA%\yt-browser-profile \
         --remote-debugging-port=9222 --remote-allow-origins=* \
         "https://accounts.google.com/ServiceLogin?continue=https://www.youtube.com/"
    2) 用户完成登录后运行:
       python yt_login_watch.py [out_cookies.txt] [deadline_seconds]
       (默认输出 %LOCALAPPDATA%\yt-cookies.txt, 等待 900 秒)

检测到 youtube 域登录态 (LOGIN_INFO / __Secure-*PSID / SAPISID / SID) 即导出并退出。
"""
import argparse
import json
import os
import sys
import time
import urllib.request

import websocket

sys.stdout.reconfigure(encoding="utf-8", errors="replace")

_ap = argparse.ArgumentParser(description="等待专用 profile 登录并导出 cookies.txt")
_ap.add_argument("out", nargs="?", default=None, help="输出路径 (默认 %%LOCALAPPDATA%%\\yt-cookies.txt)")
_ap.add_argument("deadline_s", nargs="?", type=int, default=900, help="最长等待秒数 (默认 900)")
_args = _ap.parse_args()

OUT = _args.out or os.path.expandvars(r"%LOCALAPPDATA%\yt-cookies.txt")
if os.path.abspath(OUT) != os.path.expandvars(r"%LOCALAPPDATA%\yt-cookies.txt"):
    print(f"[warn] cookies 含 Google 登录态, 输出到非常规位置时勿入库/外传: {OUT}")
DEADLINE_S = _args.deadline_s
PORT = 9222
DEADLINE = time.time() + DEADLINE_S
LOGIN_NAMES = {"LOGIN_INFO", "__Secure-1PSID", "__Secure-3PSID", "SAPISID", "SID"}

try:
    import websocket  # noqa: F401
except ImportError:
    print("ERROR: 缺依赖, 先执行: python -m pip install -U websocket-client")
    sys.exit(1)


def write_netscape(cookies, out_path):
    lines = ["# Netscape HTTP Cookie File", "# generated by yt_login_watch.py", ""]
    n = 0
    for c in cookies:
        domain = c.get("domain", "")
        name = c.get("name", "")
        if not domain or not name:
            continue
        include_sub = "TRUE" if domain.startswith(".") else "FALSE"
        secure = "TRUE" if c.get("secure") else "FALSE"
        try:
            expires = int(float(c.get("expires") or 0))
        except Exception:
            expires = 0
        if expires < 0:
            expires = 0
        prefix = "#HttpOnly_" if c.get("httpOnly") else ""
        lines.append(
            f"{prefix}{domain}\t{include_sub}\t{c.get('path', '/')}\t{secure}\t"
            f"{expires}\t{name}\t{c.get('value', '')}"
        )
        n += 1
    with open(out_path, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(lines) + "\n")
    return n


def get_ws():
    try:
        info = json.loads(
            urllib.request.urlopen(f"http://127.0.0.1:{PORT}/json/version", timeout=3).read()
        )
        return info.get("webSocketDebuggerUrl")
    except Exception:
        return None


ws_url = None
while time.time() < DEADLINE and not ws_url:
    ws_url = get_ws()
    if not ws_url:
        time.sleep(2)
if not ws_url:
    print("devtools not up (专用 Chrome 没在运行或没带 --remote-debugging-port=9222)")
    sys.exit(1)
print("connected to devtools, waiting for login...", flush=True)

while time.time() < DEADLINE:
    try:
        ws = websocket.create_connection(ws_url, timeout=20, suppress_origin=True)
        ws.send(json.dumps({"id": 1, "method": "Storage.getCookies"}))
        m = None
        while True:
            m = json.loads(ws.recv())
            if m.get("id") == 1:
                break
        ws.close()
        cookies = m.get("result", {}).get("cookies", [])
        logged = any(
            "youtube" in c.get("domain", "") and c.get("name") in LOGIN_NAMES for c in cookies
        )
        gg = any(
            "google" in c.get("domain", "") and c.get("name") in ("SID", "__Secure-1PSID")
            for c in cookies
        )
        print(f"cookies: {len(cookies)} yt_login: {logged} google_login: {gg}", flush=True)
        if logged:
            n = write_netscape(cookies, OUT)
            print(f"WROTE {n} -> {OUT}")
            sys.exit(0)
    except Exception as e:
        print("poll error:", repr(e)[:100], flush=True)
    time.sleep(5)

print("timeout waiting for login")
sys.exit(2)
