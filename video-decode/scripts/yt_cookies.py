#!/usr/bin/env python3
r"""从专用登录 profile 铸造 youtube cookies.txt (无头, 不碰用户日常浏览器)

用法: python yt_cookies.py [out.txt]
      默认输出 %LOCALAPPDATA%\yt-cookies.txt; cookies 过期后重复运行即可刷新。

- 专用 profile: %LOCALAPPDATA%\\yt-browser-profile (首次需用 yt_login_watch.py 流程登录一次)
- 若该 profile 已被带 9222 调试端口的窗口占用, 直接附着导出; 否则无头启动副本导出后关闭。
- cookies 过期后重复运行即可刷新 (profile 保持登录)。
"""
import argparse
import json
import os
import subprocess
import sys
import time
import urllib.request

try:
    import websocket  # noqa: F401
except ImportError:
    print("ERROR: 缺依赖, 先执行: python -m pip install -U websocket-client")
    sys.exit(1)

sys.stdout.reconfigure(encoding="utf-8", errors="replace")

EXE = r"C:\Program Files\Google\Chrome\Application\chrome.exe"
PROF = os.path.expandvars(r"%LOCALAPPDATA%\yt-browser-profile")
PORT = 9222


def write_netscape(cookies, out_path):
    lines = ["# Netscape HTTP Cookie File", "# generated by yt_cookies.py", ""]
    n = 0
    for c in cookies:
        domain = c.get("domain", "")
        name = c.get("name", "")
        if not domain or not name:
            continue
        include_sub = "TRUE" if domain.startswith(".") else "FALSE"
        secure = "TRUE" if c.get("secure") else "FALSE"
        try:
            expires = int(float(c.get("expires") or 0))
        except Exception:
            expires = 0
        if expires < 0:
            expires = 0
        prefix = "#HttpOnly_" if c.get("httpOnly") else ""
        lines.append(
            f"{prefix}{domain}\t{include_sub}\t{c.get('path', '/')}\t{secure}\t"
            f"{expires}\t{name}\t{c.get('value', '')}"
        )
        n += 1
    with open(out_path, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(lines) + "\n")
    return n


def get_ws():
    try:
        info = json.loads(
            urllib.request.urlopen(f"http://127.0.0.1:{PORT}/json/version", timeout=3).read()
        )
        return info.get("webSocketDebuggerUrl")
    except Exception:
        return None


def kill_profile():
    ps = (
        "Get-CimInstance Win32_Process -Filter \"Name='chrome.exe'\" | "
        "Where-Object { $_.CommandLine -like '*yt-browser-profile*' } | "
        "ForEach-Object { Stop-Process -Id $_.ProcessId -Force -ErrorAction SilentlyContinue }"
    )
    subprocess.run(["powershell", "-NoProfile", "-Command", ps], capture_output=True)


def main():
    ap = argparse.ArgumentParser(description="从专用登录 profile 铸造 youtube cookies.txt")
    ap.add_argument("out", nargs="?", default=None, help="输出路径 (默认 %%LOCALAPPDATA%%\\yt-cookies.txt)")
    args = ap.parse_args()

    default_out = os.path.expandvars(r"%LOCALAPPDATA%\yt-cookies.txt")
    out = args.out or default_out
    if os.path.abspath(out) != os.path.abspath(default_out):
        print(f"[warn] cookies 含 Google 登录态, 输出到非常规位置时勿入库/外传: {out}")
    ws_url = get_ws()
    launched = False
    if not ws_url:
        os.makedirs(PROF, exist_ok=True)
        subprocess.Popen(
            [
                EXE,
                f"--user-data-dir={PROF}",
                f"--remote-debugging-port={PORT}",
                "--headless=new",
                "--no-first-run",
                "--disable-gpu",
                "--remote-allow-origins=*",
                "about:blank",
            ],
            stdout=subprocess.DEVNULL,
            stderr=subprocess.DEVNULL,
        )
        launched = True
        for _ in range(60):
            ws_url = get_ws()
            if ws_url:
                break
            time.sleep(1)
    if not ws_url:
        raise SystemExit("devtools not up")
    print("devtools ok", "(attached)" if not launched else "(headless launched)")

    ws = websocket.create_connection(ws_url, timeout=30, suppress_origin=True)

    def cmd(i, method, params=None):
        ws.send(json.dumps({"id": i, "method": method, "params": params or {}}))
        while True:
            m = json.loads(ws.recv())
            if m.get("id") == i:
                return m

    cmd(1, "Target.createTarget", {"url": "https://www.youtube.com/"})
    time.sleep(8)
    r = cmd(2, "Storage.getCookies")
    cookies = r.get("result", {}).get("cookies", [])
    yt = [c for c in cookies if "youtube" in c.get("domain", "")]
    logged = any(c.get("name") in ("LOGIN_INFO", "__Secure-1PSID", "__Secure-3PSID") for c in yt)
    print("cookies:", len(cookies), "youtube:", len(yt), "logged_in:", logged)
    n = write_netscape(cookies, out)
    print("wrote", n, "->", out)
    ws.close()
    if launched:
        kill_profile()
    print("done")


if __name__ == "__main__":
    main()
