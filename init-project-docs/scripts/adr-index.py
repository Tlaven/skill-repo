#!/usr/bin/env python3
"""adr-index.py — generate the ADR index and check ADR metadata.

Why this exists: an agent opens a *record* far more often than it opens the
index, so whatever a record says on its own is what the agent follows. Two
consequences drive this script:

  - a superseded record must not sit in the in-force list (an agent that reads
    the file reads whatever is left in it);
  - an index kept by hand drifts in the first busy week, so it is generated.

What is checked (deterministic, no semantics):
  - IDs unique; heading is `# <ID>: <title>` and agrees with the filename
  - status is canonical; `superseded` names its replacement
  - relation fields resolve to an existing record (main dir or archive/)
  - the committed index equals the generated one
  - citations in the files an agent reads first (L1, docs/, SKILL.md, references/)
    resolve to a record; a citation to a retired record is a warning
  - with `--immutable`: a record's body may only grow (append-only) since --base
Warnings (reported, never fail on their own):
  - a superseded record still outside archive/
  - a record over 800 words (usually two decisions)
  - a citation pointing at a superseded / deprecated / rejected record

Status source: YAML frontmatter (`status: accepted`) or the legacy `## 状态`
section (first non-empty, non-comment line). Frontmatter wins, so projects can
migrate one record at a time.

Relations (frontmatter, all optional): superseded_by / partially_superseded_by /
revised_by / extended_by, and the forward forms supersedes / revises / extends.
Declared once, on the older record; the index shows only what is in force.

Index block in README.md:

    <!-- adr-index:begin ... -->
    ...generated lines...
    <!-- adr-index:end -->

Usage:
    python scripts/adr-index.py --root .            # report
    python scripts/adr-index.py --root . --write    # regenerate the index
    python scripts/adr-index.py --root . --strict   # exit 1 on findings
    python scripts/adr-index.py --root . --immutable --base HEAD   # append-only check

Exit 1 only with --strict when findings exist (warnings never fail).
"""

import argparse
import json
import os
import re
import subprocess
import sys

from _doc_common import active_mask, iter_docs, read_lines, rel

ID_RE = re.compile(r"\b([A-Za-z]{2,6}-\d{2,4})\b")
HEADING_RE = re.compile(r"^#\s+([A-Za-z]{2,6}-\d{2,4})\s*[:：]\s*(.*?)\s*$")
FILENAME_RE = re.compile(r"^(?:([A-Za-z]{2,6})[-_])?(\d{2,4})(?:[-_.]|$)")
STATUS_HEAD_RE = re.compile(r"^##\s+(?:状态|status)\s*$", re.I)

RELATION_KEYS = (
    "superseded_by",
    "partially_superseded_by",
    "revised_by",
    "extended_by",
    "supersedes",
    "partially_supersedes",
    "revises",
    "extends",
)

STANDING = ("accepted", "accepted(修订)")
PENDING = ("proposed",)
RETIRED = ("superseded", "deprecated", "rejected")

BEGIN_MARK = "<!-- adr-index:begin"
BEGIN_LINE = "<!-- adr-index:begin (generated by scripts/adr-index.py --write; do not edit by hand) -->"
END_LINE = "<!-- adr-index:end -->"

MAX_WORDS = 800
DEFAULT_DIR = os.path.join("docs", "decisions")
DEFAULT_SCAN = ("SKILL.md", "references")


def finding(tag, where, message):
    return {"tag": tag, "file": where, "message": message}


def read_raw(path):
    """Read text plus its newline style (so --write does not flip CRLF to LF)."""
    with open(path, "r", encoding="utf-8-sig", errors="replace", newline="") as f:
        text = f.read()
    newline = "\r\n" if "\r\n" in text else "\n"
    return text, newline


def write_raw(path, text, newline):
    with open(path, "w", encoding="utf-8", newline="") as f:
        f.write(text.replace("\n", newline) if newline == "\r\n" else text)


def parse_front_matter(lines):
    """Return (mapping, index of first body line). Only `key: value` scalars."""
    if not lines or lines[0].strip().lstrip("\ufeff") != "---":
        return {}, 0
    for i in range(1, len(lines)):
        if lines[i].strip() != "---":
            continue
        fm = {}
        for raw in lines[1:i]:
            line = raw.strip()
            if not line or line.startswith("#") or ":" not in line:
                continue
            key, value = line.split(":", 1)
            key = key.strip().lower().replace("-", "_").replace(" ", "_")
            value = re.split(r"\s+#", value.strip(), maxsplit=1)[0]
            value = value.strip().strip('"').strip("'")
            if value:
                fm[key] = value
        return fm, i + 1
    return {}, 0


def rel_ids(value):
    return [m.group(1).upper() for m in ID_RE.finditer(value)]


def normalize_status(raw):
    """Return (canonical status, replacement id or None).

    The status is the leading token; whatever follows it (a date, 「已落地」, 「被 ADR-0xx
    取代」) is prose, not part of the status. Only an unknown leading token is a finding.
    """
    s = raw.strip().replace("（", "(").replace("）", ")").replace("\ufeff", "")
    s = re.sub(r"^[^0-9A-Za-z\u4e00-\u9fff]+", "", s).strip()

    m = re.match(r"^superseded\s+by\s+([A-Za-z]{2,6}-\d{2,4})\b", s, re.I)
    if m:
        return "superseded", m.group(1).upper()

    low = s.lower()
    if low.startswith("accepted(修订)"):
        return "accepted(修订)", None
    for token in ("accepted", "proposed", "superseded", "deprecated", "rejected"):
        if not low.startswith(token):
            continue
        rest = low[len(token):]
        if rest and rest[0] not in "( \t:：,，.。;；-—)":
            continue
        target = None
        if token == "superseded":
            ids = rel_ids(s)
            target = ids[0] if ids else None
        return token, target
    return re.split(r"[(（\s:：,，]", s, 1)[0].strip().lower(), None


def status_of(lines, fm):
    raw = fm.get("status")
    if raw:
        return normalize_status(raw)
    start = None
    for i, line in enumerate(lines):
        if STATUS_HEAD_RE.match(line.strip()):
            start = i
            break
    if start is None:
        return "", None
    in_comment = False
    for line in lines[start + 1:]:
        s = line.strip()
        if in_comment:
            if "-->" in s:
                in_comment = False
            continue
        if s.startswith("<!--"):
            if "-->" not in s:
                in_comment = True
            continue
        if not s:
            continue
        if s.startswith("#"):
            break
        s = s.lstrip("-*").strip()
        if s:
            return normalize_status(s)
    return "", None


def word_count(text):
    """CJK characters count as words; other scripts count as whitespace tokens."""
    cjk = len(re.findall(r"[\u3400-\u4dbf\u4e00-\u9fff]", text))
    latin = len(re.findall(r"[A-Za-z0-9_][A-Za-z0-9_.+-]*", text))
    return cjk + latin


def heading_of(lines, body_start=0):
    for i in range(body_start, len(lines)):
        m = HEADING_RE.match(lines[i])
        if m:
            return m.group(1).upper(), m.group(2).strip()
    return None, ""


def parse_record(root, path, archived):
    lines = read_lines(path)
    fm, body_start = parse_front_matter(lines)
    rid, title = heading_of(lines, body_start)

    num, prefix = None, None
    m = FILENAME_RE.match(os.path.basename(path))
    if m:
        prefix = (m.group(1) or "").upper()
        num = int(m.group(2))

    status, target = status_of(lines, fm)
    relations = {}
    for key in RELATION_KEYS:
        if fm.get(key):
            relations[key] = rel_ids(fm[key])
    if target:
        relations.setdefault("superseded_by", [])
        if target not in relations["superseded_by"]:
            relations["superseded_by"].append(target)

    body = "\n".join(lines[body_start:])
    return {
        "file": rel(root, path),
        "path": path,
        "id": rid,
        "num": num,
        "prefix": prefix,
        "title": title or os.path.splitext(os.path.basename(path))[0],
        "status": status,
        "relations": relations,
        "words": word_count(body),
        "archived": archived,
    }


def collect(root, adr_dir, archived=False):
    if not os.path.isdir(adr_dir):
        return []
    records = []
    for name in sorted(os.listdir(adr_dir)):
        lower = name.lower()
        if not lower.endswith((".md", ".markdown")):
            continue
        if lower.startswith("readme") or "template" in lower:
            continue
        path = os.path.join(adr_dir, name)
        if os.path.isfile(path):
            records.append(parse_record(root, path, archived))
    return records


def template_ids(adr_dir):
    """IDs of `*template*` files: not records, but citing them is not a broken link."""
    ids = set()
    if not os.path.isdir(adr_dir):
        return ids
    for name in sorted(os.listdir(adr_dir)):
        if "template" not in name.lower():
            continue
        path = os.path.join(adr_dir, name)
        if not os.path.isfile(path):
            continue
        lines = read_lines(path)
        _, body_start = parse_front_matter(lines)
        rid, _ = heading_of(lines, body_start)
        if rid:
            ids.add(rid)
    return ids


def default_index_path(adr_dir):
    for name in ("README.md", "README.markdown", "README.MD"):
        candidate = os.path.join(adr_dir, name)
        if os.path.isfile(candidate):
            return candidate
    return os.path.join(adr_dir, "README.md")


def sort_key(record):
    return (record["num"] or 0, record["id"] or "")


def render_index(records):
    standing = sorted(
        (r for r in records if r["id"] and r["status"] in STANDING), key=sort_key, reverse=True
    )
    pending = sorted(
        (r for r in records if r["id"] and r["status"] in PENDING), key=sort_key, reverse=True
    )

    out = []
    if standing:
        out.append("**现役** — 现行约束（按编号倒序）：")
        out.append("")
        out.extend("- {} · {} · {}".format(r["id"], r["status"], r["title"]) for r in standing)
    else:
        out.append("（暂无现役记录）")
    if pending:
        out.append("")
        out.append("**在议** — 未生效，不是约束：")
        out.append("")
        out.extend("- {} · {} · {}".format(r["id"], r["status"], r["title"]) for r in pending)
    return out


def find_block(lines):
    begin = end = None
    for i, line in enumerate(lines):
        if begin is None and BEGIN_MARK in line:
            begin = i
        elif begin is not None and END_LINE in line:
            end = i
            break
    return begin, end


def validate(records, archived_ids, max_words=MAX_WORDS):
    findings, warnings = [], []
    by_id = {}
    for record in records:
        if record["id"]:
            by_id.setdefault(record["id"], []).append(record)

    for rid, group in sorted(by_id.items()):
        if len(group) > 1:
            findings.append(finding(
                "adr-id-duplicate",
                rid,
                "same ID on " + ", ".join(r["file"] for r in group),
            ))

    known = set(by_id) | set(archived_ids)
    allowed = ", ".join(STANDING + PENDING + RETIRED)

    for record in records:
        where = record["file"]
        if not record["id"]:
            findings.append(finding(
                "adr-heading-mismatch",
                where,
                "missing '# <ID>: <title>' heading (e.g. '# ADR-003: Use event sourcing')",
            ))
        elif record["num"] is not None:
            id_prefix, _, id_num = record["id"].partition("-")
            if record["num"] != int(id_num):
                findings.append(finding(
                    "adr-name-mismatch",
                    where,
                    "filename number does not match heading ID {}".format(record["id"]),
                ))
            elif record["prefix"] and record["prefix"] != id_prefix:
                findings.append(finding(
                    "adr-name-mismatch",
                    where,
                    "filename prefix '{}' does not match heading ID {}".format(record["prefix"], record["id"]),
                ))

        if not record["status"]:
            findings.append(finding(
                "adr-bad-status",
                where,
                "missing status (frontmatter `status:` or a `## 状态` section)",
            ))
        elif record["status"] not in STANDING + PENDING + RETIRED:
            findings.append(finding(
                "adr-bad-status",
                where,
                "status '{}' is not canonical (allowed: {})".format(record["status"], allowed),
            ))

        if record["status"] == "superseded" and not record["relations"].get("superseded_by"):
            findings.append(finding(
                "adr-superseded-no-target",
                where,
                "superseded but names no replacement (`superseded_by: ADR-XXX`)",
            ))

        for key, ids in sorted(record["relations"].items()):
            for target in ids:
                if target not in known:
                    findings.append(finding(
                        "adr-relation-missing",
                        where,
                        "{}: {} does not exist (main dir or archive/)"
                        .format(key, target),
                    ))

        if record["status"] == "superseded" and not record["archived"]:
            warnings.append(finding(
                "adr-archive",
                where,
                "superseded but still in the main dir; move it to archive/ so a directory listing does not surface it",
            ))

        if record["words"] > max_words:
            warnings.append(finding(
                "adr-long",
                where,
                "{} words > {} — usually two decisions, or an implementation diary"
                .format(record["words"], max_words),
            ))

    return findings, warnings


def check_ignore(root, adr_dir):
    """A moved record is only invisible to rg if .ignore says so; the failure is silent."""
    archive = os.path.join(adr_dir, "archive")
    if not os.path.isdir(archive):
        return []
    if not any(n.lower().endswith((".md", ".markdown")) for n in os.listdir(archive)):
        return []

    entries = set()
    ignore = os.path.join(adr_dir, ".ignore")
    if os.path.isfile(ignore):
        with open(ignore, "r", encoding="utf-8-sig", errors="replace") as f:
            for line in f:
                line = line.strip()
                if not line or line.startswith("#"):
                    continue
                line = line.strip("/").lower()
                if line.endswith("/**"):
                    line = line[:-3].rstrip("/")
                entries.add(line)
    if "archive" in entries:
        return []
    return [finding(
        "adr-no-ignore",
        rel(root, archive),
        "archive/ is still searched by rg; add `archive/` to {}/.ignore".format(rel(root, adr_dir)),
    )]


def check_citations(root, records, archived_records, scan_extra, extra_known=()):
    """ADR ids mentioned in the files an agent reads first must still stand."""
    known = {}
    for record in records + archived_records:
        if record["id"]:
            known[record["id"]] = record["status"]
    for rid in extra_known:
        known.setdefault(rid, "")

    paths = list(iter_docs(root))
    for extra in scan_extra:
        target = os.path.join(root, extra)
        if os.path.isfile(target):
            paths.append(target)
        elif os.path.isdir(target):
            for dirpath, _, filenames in os.walk(target):
                for name in sorted(filenames):
                    if name.endswith((".md", ".markdown")):
                        paths.append(os.path.join(dirpath, name))

    findings, warnings = [], []
    seen = set()
    for path in paths:
        try:
            lines = read_lines(path)
        except OSError:
            continue
        mask = active_mask(lines)
        for lineno, (line, skip) in enumerate(zip(lines, mask), 1):
            if skip:
                continue
            for match in ID_RE.finditer(line):
                rid = match.group(1).upper()
                where = "{}:{}".format(rel(root, path), lineno)
                if (where, rid) in seen:
                    continue
                seen.add((where, rid))
                if rid not in known:
                    findings.append(finding(
                        "adr-cite-missing",
                        where,
                        "{} does not exist (main dir or archive/)".format(rid),
                    ))
                elif known[rid] in RETIRED:
                    warnings.append(finding(
                        "adr-cite-retired",
                        where,
                        "{} is {}; cite the record that stands, or drop the reference"
                        .format(rid, known[rid]),
                    ))
    return findings, warnings


def git_run(root, *args):
    return subprocess.run(
        ["git", "-C", root] + list(args),
        capture_output=True,
        text=True,
        encoding="utf-8",
        errors="replace",
    )


def normalized_body(lines):
    """Body with frontmatter and the superseded note removed; blank runs collapsed."""
    _, body_start = parse_front_matter(lines)
    out = []
    for line in lines[body_start:]:
        stripped = line.strip()
        if stripped.startswith(">") and "superseded by" in stripped.lower():
            continue
        value = line.rstrip()
        if not value and out and not out[-1]:
            continue
        out.append(value)
    while out and not out[-1]:
        out.pop()
    return out


def check_immutability(root, dir_rel, records, archived_records, base):
    """A record's body may only grow: append-only, so old lines must survive as a prefix."""
    listing = git_run(root, "ls-tree", "-r", "--name-only", base, "--", dir_rel)
    if listing.returncode != 0:
        return None

    old = {}
    for path in listing.stdout.splitlines():
        path = path.strip()
        name = os.path.basename(path).lower()
        if not path.lower().endswith((".md", ".markdown")):
            continue
        if name.startswith("readme") or "template" in name:
            continue
        shown = git_run(root, "show", "{}:{}".format(base, path))
        if shown.returncode != 0:
            continue
        lines = shown.stdout.splitlines()
        _, body_start = parse_front_matter(lines)
        rid, _ = heading_of(lines, body_start)
        if rid:
            old[rid] = (path, normalized_body(lines))

    current = {r["id"]: r for r in records + archived_records if r["id"]}
    findings = []
    for rid, (path, old_body) in sorted(old.items()):
        if rid not in current:
            findings.append(finding(
                "adr-deleted",
                path,
                "{} existed at {} but is gone; move it to archive/ instead of deleting"
                .format(rid, base),
            ))
            continue
        record = current[rid]
        new_body = normalized_body(read_lines(record["path"]))
        if new_body[:len(old_body)] == old_body and len(new_body) >= len(old_body):
            continue
        first = next(
            (i for i, (a, b) in enumerate(zip(old_body, new_body)) if a != b),
            min(len(old_body), len(new_body)),
        )
        findings.append(finding(
            "adr-immutable",
            record["file"],
            "body changed since {} near body line {}; records are append-only "
            "(frontmatter, the superseded note, and appending a 补充 are allowed)"
            .format(base, first + 1),
        ))
    return findings


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--root", default=".", help="project root (default: .)")
    ap.add_argument("--dir", default=DEFAULT_DIR, help="ADR directory relative to root (default: docs/decisions)")
    ap.add_argument("--index", default="", help="index file relative to root (default: <dir>/README.md or README.markdown)")
    ap.add_argument("--write", action="store_true", help="regenerate the index block in place")
    ap.add_argument("--strict", action="store_true", help="exit 1 on findings (warnings never fail)")
    ap.add_argument("--citations", dest="citations", action="store_true", default=True,
                    help="check ADR citations in L1 / docs / SKILL.md / references (default: on)")
    ap.add_argument("--no-citations", dest="citations", action="store_false",
                    help="skip the citation check")
    ap.add_argument("--scan", action="append", default=[],
                    help="extra file or dir to scan for citations (repeatable)")
    ap.add_argument("--immutable", action="store_true",
                    help="fail when a record body changed since --base (append-only)")
    ap.add_argument("--base", default="HEAD", help="git ref for --immutable (default: HEAD)")
    ap.add_argument("--max-words", type=int, default=MAX_WORDS,
                    help="warn above this many words per record (default: 800)")
    ap.add_argument("--json", help="write JSON report to this path")
    args = ap.parse_args()

    root = os.path.abspath(args.root)
    adr_dir = os.path.join(root, args.dir)
    index_path = os.path.join(root, args.index) if args.index else default_index_path(adr_dir)

    if not os.path.isdir(adr_dir):
        if args.json:
            with open(args.json, "w", encoding="utf-8") as f:
                json.dump({"records": [], "findings": [], "warnings": [], "index": None}, f, ensure_ascii=False, indent=2)
        print("[adr-index] no ADR directory at {}; nothing to do.".format(args.dir.replace("\\", "/")))
        return 0

    records = collect(root, adr_dir)
    archived_records = collect(root, os.path.join(adr_dir, "archive"), archived=True)
    archived_ids = {r["id"] for r in archived_records if r["id"]}

    findings, warnings = validate(records, archived_ids, args.max_words)

    if args.citations:
        cite_findings, cite_warnings = check_citations(
            root, records, archived_records, list(DEFAULT_SCAN) + args.scan,
            extra_known=template_ids(adr_dir),
        )
        findings += cite_findings
        warnings += cite_warnings

    warnings += check_ignore(root, adr_dir)

    if args.immutable:
        immutable = check_immutability(root, args.dir, records, archived_records, args.base)
        if immutable is None:
            print("[adr-immutable] skipped: not a git repo, or '{}' not found".format(args.base))
        else:
            findings += immutable

    generated = render_index(records)

    created = False
    drift = False
    wrote = False
    if not os.path.isfile(index_path):
        if args.write:
            os.makedirs(os.path.dirname(index_path) or ".", exist_ok=True)
            write_raw(
                index_path,
                "# Architecture Decision Records (ADR)\n\n## ADR 索引\n\n"
                + BEGIN_LINE + "\n" + "\n".join(generated) + "\n" + END_LINE + "\n",
                "\n",
            )
            created = wrote = True
        else:
            findings.append(finding(
                "adr-index-missing",
                rel(root, index_path),
                "index file not found; run --write to create it",
            ))
            drift = True
    if not created and os.path.isfile(index_path):
        text, newline = read_raw(index_path)
        lines = text.splitlines()
        begin, end = find_block(lines)
        if begin is None or end is None:
            findings.append(finding(
                "adr-index-missing",
                rel(root, index_path),
                "no `{}` / `{}` markers".format(BEGIN_MARK + " -->", END_LINE),
            ))
            drift = True
        else:
            current = "\n".join(lines[begin + 1:end]).strip()
            drift = current != "\n".join(generated).strip()
            if drift and args.write:
                rebuilt = lines[:begin] + [BEGIN_LINE] + generated + [END_LINE] + lines[end + 1:]
                trailing = "\n" if text.endswith(("\n", "\r")) else ""
                write_raw(index_path, "\n".join(rebuilt) + trailing, newline)
                wrote = True
            elif drift:
                findings.append(finding(
                    "adr-index-drift",
                    rel(root, index_path),
                    "index differs from records; run --write (never edit the block by hand)",
                ))

    for item in findings:
        print("[{}] {}: {}".format(item["tag"], item["file"], item["message"]))

    long_warnings = [w for w in warnings if w["tag"] == "adr-long"]
    for item in warnings:
        if item["tag"] != "adr-long":
            print("[{}] {}: {}".format(item["tag"], item["file"], item["message"]))
    if 0 < len(long_warnings) <= 3:
        for item in long_warnings:
            print("[{}] {}: {}".format(item["tag"], item["file"], item["message"]))
    elif long_warnings:
        longest = sorted(
            (r for r in records if r["id"] and r["words"] > args.max_words),
            key=lambda r: r["words"], reverse=True,
        )[:3]
        print("[adr-long] {} of {} records exceed {} words (longest: {}); "
              "raise --max-words if long records are the house style".format(
                  len(long_warnings), len(records), args.max_words,
                  ", ".join("{} {}".format(r["id"], r["words"]) for r in longest)))

    standing = sum(1 for r in records if r["id"] and r["status"] in STANDING)
    pending = sum(1 for r in records if r["id"] and r["status"] in PENDING)
    retired = sum(1 for r in records if r["id"] and r["status"] in RETIRED)

    if args.json:
        with open(args.json, "w", encoding="utf-8") as f:
            json.dump(
                {
                    "dir": args.dir.replace("\\", "/"),
                    "index": rel(root, index_path),
                    "drift": drift,
                    "generated": generated,
                    "records": [
                        {
                            "file": r["file"],
                            "id": r["id"],
                            "status": r["status"],
                            "archived": r["archived"],
                            "relations": r["relations"],
                            "words": r["words"],
                        }
                        for r in records
                    ],
                    "findings": findings,
                    "warnings": warnings,
                },
                f,
                ensure_ascii=False,
                indent=2,
            )

    if args.write:
        if created:
            print("[adr-index] created {}".format(rel(root, index_path)))
        elif wrote:
            print("[adr-index] regenerated {}".format(rel(root, index_path)))
        else:
            print("[adr-index] index already up to date.")
    print("[adr-index] {} standing, {} proposed, {} retired; {} finding(s), {} warning(s).".format(
        standing, pending, retired, len(findings), len(warnings)))

    return 1 if (args.strict and findings) else 0


if __name__ == "__main__":
    sys.exit(main())
